CREATE TABLE TB_CC_USUARIO (
  ID_USUARIO   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOME_USUARIO VARCHAR2(100) NOT NULL,
  EMAIL        VARCHAR2(100) NOT NULL,
  SENHA        VARCHAR2(100) NOT NULL,
  CONSTRAINT PK_CC_USUARIO PRIMARY KEY (ID_USUARIO),
  CONSTRAINT UK_CC_USUARIO_EMAIL UNIQUE (EMAIL)
);

COMMENT ON TABLE  TB_CC_USUARIO              IS 'Tutor responsavel pelo animal. Faz parte do CORE porque cada pet pertence a um tutor que recebe o monitoramento preditivo.';
COMMENT ON COLUMN TB_CC_USUARIO.ID_USUARIO   IS 'PK do tutor responsavel pelo pet';
COMMENT ON COLUMN TB_CC_USUARIO.NOME_USUARIO IS 'Nome completo do tutor';
COMMENT ON COLUMN TB_CC_USUARIO.EMAIL        IS 'E-mail de contato do tutor para alertas de saude';
COMMENT ON COLUMN TB_CC_USUARIO.SENHA        IS 'Credencial de cadastro do tutor no aplicativo';

CREATE TABLE TB_CC_PET (
  ID_PET        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOME_PET      VARCHAR2(100) NOT NULL,
  ESPECIE       VARCHAR2(50)  NOT NULL,
  DT_NASCIMENTO DATE          NOT NULL,
  ID_USUARIO    NUMBER        NOT NULL,
  CONSTRAINT PK_CC_PET PRIMARY KEY (ID_PET),
  CONSTRAINT FK_CC_PET_TUTOR FOREIGN KEY (ID_USUARIO)
    REFERENCES TB_CC_USUARIO (ID_USUARIO)
);

CREATE INDEX IDX_CC_PET_TUTOR   ON TB_CC_PET (ID_USUARIO);
CREATE INDEX IDX_CC_PET_ESPECIE ON TB_CC_PET (ESPECIE);

COMMENT ON TABLE  TB_CC_PET               IS 'Animal monitorado pela plataforma. Tabela CORE da solucao de saude preditiva.';
COMMENT ON COLUMN TB_CC_PET.ID_PET        IS 'PK do animal monitorado';
COMMENT ON COLUMN TB_CC_PET.NOME_PET      IS 'Nome do pet';
COMMENT ON COLUMN TB_CC_PET.ESPECIE       IS 'Especie do animal (Cachorro, Gato, etc.)';
COMMENT ON COLUMN TB_CC_PET.DT_NASCIMENTO IS 'Data de nascimento usada no calculo de risco por faixa etaria';
COMMENT ON COLUMN TB_CC_PET.ID_USUARIO    IS 'FK do tutor responsavel pelo pet';

CREATE TABLE TB_CC_LOG_SAUDE (
  ID_LOG               NUMBER GENERATED BY DEFAULT AS IDENTITY,
  PESO                 NUMBER(10,2)  NOT NULL,
  TEMPERATURA          NUMBER(10,2)  NOT NULL,
  BATIMENTOS_CARDIACOS NUMBER        NOT NULL,
  DATA_HORA            TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  OBSERVACOES          VARCHAR2(500),
  ID_PET               NUMBER        NOT NULL,
  CONSTRAINT PK_CC_LOG_SAUDE PRIMARY KEY (ID_LOG),
  CONSTRAINT FK_CC_LOG_PET FOREIGN KEY (ID_PET)
    REFERENCES TB_CC_PET (ID_PET) ON DELETE CASCADE
);

CREATE INDEX IDX_CC_LOG_PET  ON TB_CC_LOG_SAUDE (ID_PET);
CREATE INDEX IDX_CC_LOG_DATA ON TB_CC_LOG_SAUDE (DATA_HORA);

COMMENT ON TABLE  TB_CC_LOG_SAUDE                    IS 'Historico de sinais vitais do pet. Tabela CORE usada para deteccao precoce de anomalias.';
COMMENT ON COLUMN TB_CC_LOG_SAUDE.ID_LOG             IS 'PK da leitura biometrica';
COMMENT ON COLUMN TB_CC_LOG_SAUDE.PESO               IS 'Peso em kg coletado pelo dispositivo IoT';
COMMENT ON COLUMN TB_CC_LOG_SAUDE.TEMPERATURA        IS 'Temperatura corporal em Celsius (faixa valida 30 a 45)';
COMMENT ON COLUMN TB_CC_LOG_SAUDE.BATIMENTOS_CARDIACOS IS 'Frequencia cardiaca em bpm';
COMMENT ON COLUMN TB_CC_LOG_SAUDE.DATA_HORA          IS 'Instante da coleta da leitura';
COMMENT ON COLUMN TB_CC_LOG_SAUDE.OBSERVACOES        IS 'Observacao clinica ou contexto da coleta';
COMMENT ON COLUMN TB_CC_LOG_SAUDE.ID_PET             IS 'FK do pet ao qual a leitura pertence';

